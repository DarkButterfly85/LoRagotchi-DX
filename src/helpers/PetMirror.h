// PetMirror: a DisplayDriver that draws into memory instead of onto the OLED, plus an encoder that
// turns each frame into one short text line for the dashboard page (watch the pet on a big screen).
//
// Line format (one JSON object per line, only while a dashboard page is asking for it):
//   {"pet":{"s":SEQ,"k":KEY,"d":"BASE64"}}                                  a frame
//   ... plus  "n":"fox","x":SEX,"m":MONTHS,"c":COUNT,"i":INDEX              on key frames
// The frame is 128x64 pixels, 16 bytes a row, top row first, leftmost pixel = top bit.  Unless KEY is 1
// the data is the XOR with the previous frame.  The bytes are run-length coded: a 0x00 is followed by
// how many zero bytes it stands for (1..255); every other byte stands for itself.

