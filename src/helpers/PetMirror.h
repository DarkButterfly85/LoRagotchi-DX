class PetMirror : public DisplayDriver {
public:
  uint8_t fb[PM_BYTES];
  PetMirror() : DisplayDriver(PM_W, PM_H), _sz(1), _cx(0), _cy(0) { memset(fb, 0, sizeof(fb)); }

  bool isOn() override { return true; }
  void turnOn() override {}
  void turnOff() override {}
  void clear() override { memset(fb, 0, sizeof(fb)); }
  void startFrame(ColorVal = 0) override { memset(fb, 0, sizeof(fb)); _sz = 1; _cx = _cy = 0; }
  void endFrame() override {}
  void setTextSize(int sz) override { _sz = sz < 1 ? 1 : sz; }
  void setColor(ColorVal) override {}
  void setCursor(int x, int y) override { _cx = x; _cy = y; }
  uint16_t getTextWidth(const char* s) override { return (uint16_t)(strlen(s) * 6 * _sz); }
  void print(const char* s) override {
    for (; *s; s++) {
      unsigned char ch = (unsigned char)*s;
      if (ch >= 32 && ch <= 126) {
        const uint8_t* g = pm_font + (ch - 32) * 5;
        for (int col = 0; col < 5; col++)
          for (int row = 0; row < 7; row++)
            if (g[col] & (1 << row)) fillRect(_cx + col * _sz, _cy + row * _sz, _sz, _sz);
      }
      _cx += 6 * _sz;
    }
  }
  void fillRect(int x, int y, int w, int h) override {
    for (int j = y; j < y + h; j++) for (int i = x; i < x + w; i++) set(i, j);
  }
  void drawRect(int x, int y, int w, int h) override {
    fillRect(x, y, w, 1); fillRect(x, y + h - 1, w, 1); fillRect(x, y, 1, h); fillRect(x + w - 1, y, 1, h);
  }
  void drawXbm(int x, int y, const uint8_t* bits, int w, int h) override {
    int stride = (w + 7) / 8;
    for (int j = 0; j < h; j++) for (int i = 0; i < w; i++)
      if (bits[j * stride + (i >> 3)] & (0x80 >> (i & 7))) set(x + i, y + j);
  }

private:
  int _sz, _cx, _cy;
  void set(int x, int y) { if (x >= 0 && x < PM_W && y >= 0 && y < PM_H) fb[y * (PM_W / 8) + (x >> 3)] |= 0x80 >> (x & 7); }
};

// Turns frames into dashboard lines.  Call line() for every frame; it returns 0 when there is
// nothing worth sending (the picture did not change).
struct PetMirrorEncoder {
  uint8_t prev[PM_BYTES];
  uint32_t seq, last_call, last_sent, frames_since_key;
  PetMirrorEncoder() : seq(0), last_call(0), last_sent(0), frames_since_key(0xFFFF) { memset(prev, 0, sizeof(prev)); }

  static size_t b64(const uint8_t* in, size_t n, char* out) {
    static const char T[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    size_t o = 0;
    for (size_t i = 0; i < n; i += 3) {
      uint32_t v = (uint32_t)in[i] << 16 | (i + 1 < n ? (uint32_t)in[i + 1] << 8 : 0) | (i + 2 < n ? in[i + 2] : 0);
      out[o++] = T[(v >> 18) & 63]; out[o++] = T[(v >> 12) & 63];
      out[o++] = i + 1 < n ? T[(v >> 6) & 63] : '=';
      out[o++] = i + 2 < n ? T[v & 63] : '=';
    }
    return o;
  }

  // meta fields only go out on key frames
  size_t line(const uint8_t* fb, uint32_t now, char* out, size_t cap, const char* name, int sex, int months, int count, int index, const char* uname = "") {
    if (cap < 2000) return 0;
    bool key = frames_since_key >= 40 || (uint32_t)(now - last_call) > 1500;     // first frame, every ~5 s, or after a pause
    last_call = now;
    static uint8_t d[PM_BYTES], rle[PM_BYTES + 8];
    bool any = false;
    for (int i = 0; i < PM_BYTES; i++) { d[i] = key ? fb[i] : (uint8_t)(fb[i] ^ prev[i]); if (d[i]) any = true; }
    if (!key && !any && (uint32_t)(now - last_sent) < 1000) return 0;
    size_t n = 0;
    for (int i = 0; i < PM_BYTES;) {
      if (d[i]) { rle[n++] = d[i++]; continue; }
      int run = 0; while (i < PM_BYTES && !d[i] && run < 255) { run++; i++; }
      rle[n++] = 0; rle[n++] = (uint8_t)run;
    }
    int w = snprintf(out, cap, "{\"pet\":{\"s\":%lu,\"k\":%d,", (unsigned long)(++seq), key ? 1 : 0);
    if (key) w += snprintf(out + w, cap - w, "\"n\":\"%s\",\"u\":\"%s\",\"x\":%d,\"m\":%d,\"c\":%d,\"i\":%d,", name, uname ? uname : "", sex, months, count, index);
    w += snprintf(out + w, cap - w, "\"d\":\"");
    w += (int)b64(rle, n, out + w);
    w += snprintf(out + w, cap - w, "\"}}");
    memcpy(prev, fb, PM_BYTES);
    frames_since_key = key ? 0 : frames_since_key + 1;
    last_sent = now;
    return (size_t)w;
  }
};
